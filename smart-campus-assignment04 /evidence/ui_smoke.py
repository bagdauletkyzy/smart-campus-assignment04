from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={'width':1100,'height':800})
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.goto('http://localhost:8080/')
    print('rooms initially:', pg.inner_text('#count'))
    pg.fill('#attendees','100'); pg.dispatch_event('#attendees','input')
    print('empty state:', pg.inner_text('#rooms'))
    pg.fill('#attendees','15'); pg.dispatch_event('#attendees','input')
    pg.check('input[value=projector]')
    print('15+projector:', pg.inner_text('#count'))
    pg.check('input[name=room][value=R102]', force=True)
    pg.fill('#start','10:30'); pg.fill('#end','11:30'); pg.click('#check')
    print('R102 10:30-11:30 ->', pg.inner_text('#result').replace('\n',' | '))
    pg.check('input[name=room][value=R103]', force=True)
    print('after switch ->', pg.inner_text('#result'))
    pg.click('#check'); print('R103 ->', pg.inner_text('#result').replace('\n',' | '))
    pg.screenshot(path='evidence/screenshots/desktop_1100px.png', full_page=True)
    pg.set_viewport_size({'width':360,'height':800})
    sw = pg.evaluate('document.documentElement.scrollWidth')
    print('mobile 360px scrollWidth:', sw)
    pg.screenshot(path='evidence/screenshots/mobile_360px.png', full_page=True)
    print('JS errors:', errs)
    b.close()
